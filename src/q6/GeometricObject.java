package q6;

/**
 * GeometricObject interface defining standard geometric calculations.
 */
public interface GeometricObject {
    /**
     * Calculates the perimeter of the geometric object.
     * @return perimeter as a double
     */
    double getPerimeter();

    /**
     * Calculates the area of the geometric object.
     * @return area as a double
     */
    double getArea();
}
